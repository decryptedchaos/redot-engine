#pragma once

#include "core/string/ustring.h"
#include "core/templates/vector.h"

class Viewport;

/// String builders for the two informational labels. All functions are main-thread only.
class DebugMenuInfo {
public:
	/// Hardware/software line block. `p_driver_info` comes from
	/// `OS::get_video_adapter_driver_info()` and may be empty.
	static String build_information(const Vector<String> &p_driver_info);

	/// Project/viewport/rendering settings block.
	static String build_settings(Viewport *p_viewport);

	/// Maps the project's rendering method to the add-on's display name.
	static String renderer_name(const String &p_rendering_method);
};
